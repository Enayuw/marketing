package com.br.marketing.dto.userinfo;

public class CodeValue {
    private String code;
    private Object value;

    public CodeValue() {
    }

    public String getCode() {
        return this.code;
    }

    public Object getValue() {
        return this.value;
    }

    public void setCode(String code) {
        this.code = code;
    }

    public void setValue(Object value) {
        this.value = value;
    }

}
